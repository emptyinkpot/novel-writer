import { AUTHOR_VOICE_CONTRACT } from '../shared/system-prompt.mjs';
import { CONTINUOUS_PROSE_FORMAT_CONTRACT } from '../shared/format-contract.mjs';

export function buildEnrichmentPrompt({
  topic,
  targetWordCount,
  minChars,
  maxChars,
  writingBrief,
  outlineRoute,
  body,
  factBoundary,
  currentEffectiveChars,
  neededEffectiveChars,
  targetEffectiveChars,
  maxAddedEffectiveChars,
  currentRawChars,
  targetRawChars,
  maxAddedRawChars,
  supplementalMaterials,
  retryFeedback,
}) {
  const retryText = String(retryFeedback || '').trim();
  return [
    retryText ? `[重试纠正] ${retryText}` : '',
    AUTHOR_VOICE_CONTRACT,
    '',
    '[ROLE] Enrichment Agent / 续写补充材料 Agent',
    '你属于 Writing 层。你的任务不是尾部续写，不是审稿，不是重写摘要。你的任务是在一篇已经完成的正文内部，选择少数准确位置，写入有来源材料支持的事实、动作和因果。',
    '你只回答一个问题：哪里缺少已有来源支撑的证据。不要补观点、补景色、补结构、补结论或替 Author Agent 重新写作。',
    '',
    `[主题] ${topic}`,
    `[目标长度窗口] 目标约 ${targetWordCount} 字，允许范围 ${minChars}-${maxChars} 字。`,
    currentEffectiveChars ? `[当前有效正文长度] ${currentEffectiveChars}。有效长度按中文正文字符或非空白正文字符估算，不按 Markdown、空格、标点和内部标签凑数。` : '',
    targetEffectiveChars ? `[本次补充后的目标有效长度] 约 ${targetEffectiveChars}，必须留在 ${minChars}-${maxChars} 窗口内。` : '',
    neededEffectiveChars ? `[建议新增有效正文] 约 ${neededEffectiveChars} 个有效字。` : '',
    maxAddedEffectiveChars ? `[新增上限] 本次最多只能新增约 ${maxAddedEffectiveChars} 个有效字；超过这个量会导致文章超出目标窗口。` : '',
    currentRawChars ? `[当前原始正文长度] ${currentRawChars} 字符。` : '',
    targetRawChars ? `[本次补充后的原始长度目标] 约 ${targetRawChars} 字符，必须低于 ${maxChars}。` : '',
    maxAddedRawChars ? `[原始长度新增上限] 本次最多只能新增约 ${maxAddedRawChars} 个原始字符，包括标点、换行和空格。` : '',
    '',
    '[硬边界]',
    '- 只输出合法 JSON，不要 Markdown 代码块，不要解释文字。',
    '- JSON 结构必须是：{"insertions":[{"after":"原文中连续出现且只出现一次的短句","text":"要插入的通顺中文补充句"}]}',
    '- insertions 最多 8 条。after 必须逐字复制 DRAFT 中的连续短句，且必须唯一出现。',
    '- text 必须是可以直接接在 after 后面的通顺中文正文，不能是说明、报告、标题、列表或插入指令。',
    '- 不得删除、压缩、摘要化或重写原文已有段落。你只负责写 insertions，runtime 会把它们插回原文。',
    '- 所有 insertion 合计应接近建议新增有效正文，且不得超过新增上限。如果建议新增有效正文超过 1000 字，通常需要 5-8 条 insertions，分散补入正文中段的薄弱位置。',
    '- 不从最后一段机械续写，不新增尾巴，不新增结尾，不写附录式补充。',
    '- 只能补事实、动作、时间节点、会议、文件、机构、资源流向和可核查因果。不能补观点、总结、升华、理论评价或原因清单。',
    '- text 不得使用“因此”“可见”“这说明”“归根结底”“从这个意义上说”“换句话说”来引出总结。',
    '- 不新增无来源事实、年份、数字、人物、机构、引语、文件名、地点、私人心理或现场细节。新材料只能来自 [SUPPLEMENTAL_MATERIALS]、FACT_NOTES 或正文已出现事实对象。',
    '- 不改变正文主线、作者声部、事实顺序和主要论证方向。',
    '- 凡是改动原文，都必须保证语句通顺，新增句子要和前后句自然衔接。',
    '- 不能把新增材料塞成孤立段落。优先在已有段落内部或相邻段落之间补入承接自然的事实动作、代价、场景或因果。',
    '- 不把一处薄弱点补成过长小节。补充应分散到多个薄弱位置，保持文章节奏均匀。',
    '- 如果正文已经接近上限，只做必要短补，不得为了“完整”继续扩写。',
    '',
    '[补充策略]',
    '先通读全文，识别哪些地方跳得太快、事实承重不足、场景动作缺少、因果桥太薄，或材料组之间过渡突然。',
    '再从 [SUPPLEMENTAL_MATERIALS]、FACT_NOTES、CONTEXT_BRIEF、CONTEXT_SYNTHESIS 和事实边界中选择已经支持且正文没有重复写过的材料，补到它应该出现的位置。',
    '补充目标按有效正文长度计算，不按原始字符串长度计算。新增内容必须是真正文义内容，不能靠空格、标点、换行、重复标题或格式符号增加长度。',
    '同时要服从原始长度上限。少用列表式换行、重复标点、解释性括号和松散空行；不要让 raw body 超过目标窗口。',
    '补充不是重写全文，也不是把所有可用材料都倒进去。保留原文绝大多数句子和段落顺序，只在少数薄弱位置补入必要材料。',
    '如果可补材料很多，也只选最能服务主线、且与正文现有段落不重复的少数材料；宁可少补一点，也不能超过目标长度窗口。',
    '如果 Outline Route 提到“低频使用”或“舍弃建议”，它只限制美学旁照和弱相关材料；不能因此压缩骨干事实。骨干事实的主体、制度动作、资源流向、承受者和后果应补充分明。',
    '每条 insertion 应像原文自然长出的句子，而不是原文外加的说明。不要重复正文已有表达。',
    '',
    CONTINUOUS_PROSE_FORMAT_CONTRACT,
    '',
    '[FACT_BOUNDARY]',
    factBoundary || '只能使用原文、FACT_NOTES、CONTEXT_BRIEF、CONTEXT_SYNTHESIS 已经出现或明确允许的事实对象。',
    '',
    '[SUPPLEMENTAL_MATERIALS]',
    supplementalMaterials || '无额外 DataBase/RAG/Web 补充材料。只能使用正文和 writingBrief 中已有材料。',
    '',
    '[WRITING_BRIEF]',
    writingBrief.text,
    '',
    '[OUTLINE_ROUTE]',
    outlineRoute?.text || '',
    '',
    '[DRAFT]',
    body,
  ].filter(Boolean).join('\n');
}
