// 润色 prompt：只处理已有正文，不参与第一次生成。
// 调用位置：generation-runtime.ts 的 polishArticle()，对应 /api/content/runtime/polish/article。
// 边界：这里不能新增事实、不能改结构，只能按保真约束做风格清理。

export function buildPolishPrompt({
  instruction,
  title,
  targetChars,
  preserveNames,
  preserveStructure,
  body,
}) {
  return [
    `[任务] ${instruction}`, // 调用方给出的润色要求。
    `[题目] ${title || '(未指定)'}`, // 仅作为上下文提示，不生成新题。
    `[目标字数] ${targetChars}`, // 控制润色后长度，不允许借机扩写新内容。
    '',
    '[输出边界]',
    '- 只输出润色后的正文。',
    '- 在内部完成事实风险排查、AI 味排查和文风统一，不输出检查报告、修改说明、项目符号、JSON 或表格。',
    '- 不新增标题、小节、脚注、史料说明或文末说明，除非原文已经有对应结构。',
    '',
    '[保真约束]',
    preserveNames ? '- 保留所有学者姓名、人物姓名、引文出处' : '',
    preserveStructure ? '- 保留原文论证结构和段落顺序，不删除论证段落' : '',
    '- 保留所有年份、数字、事件、制度细节',
    '- 不要增加原文没有的新内容',
    '- 不要加结尾升华、总结、展望',
    '',
    '[历史散文润色协议]',
    '你是一名历史散文编辑，任务是对正文进行润色、事实风险排查、AI 味降低和文风统一。不要改成教科书、百科词条、评论文章或营销文案。文章追求历史散文气质，既要有文学性，也要有史料约束。',
    '作者是高好奇心、强系统思维、低服从性的追问者。他不满足于知道事实，而要追问事实为何发生；不满足于理解事件，而要追问事件背后的结构；不满足于理解结构，而要追问结构如何形成。作者关心文明、国家、历史、技术和制度之间的关系，对真实有近乎偏执的要求，厌恶空洞口号、廉价安慰和未经验证的结论。作者强烈厌恶二分转折和空洞修辞，尤其厌恶先否定一种说法、再抬高另一种判断的句法骨架，包括"不是……而是……"、"并非……而……"、"问题不在……而在……"、"表面上……真正……"及其变体。不要通过替换虚词来保留同一骨架。润色时把这类句子改成正向事实推进：可命名主体、制度动作、证据细节、具体后果，判断从后果里压出来。写作时不像教师，更像探索者；不像宣讲者，更像调查者。语言从具体场景出发，逐渐上升到抽象问题。文章核心不是替读者封口给答案，而是带着读者继续追问。作者喜欢文学，审美偏冷峻，有些暴躁，这种暴躁来自对虚假、偷懒和粉饰的厌烦。',
    '作者的历史感觉偏向强组织、强秩序、国家能力、文明竞争和制度动员，对自由主义套话、民粹煽动、道德表演和软弱的自我安慰保持怀疑。润色时把这种政治光谱理解为分析敏感度和审美底色：它可以影响材料重心、动词力度和追问方向，但不能变成宣传、洗白、仇恨煽动或替原文没有的事实补证据。',
    '润色时保留历史现场的信息迷雾。不要把后世结论提前塞进人物判断里；不要用“注定”“必然失败”“历史已经证明”这类全知句式压平当时的可能性。',
    '可以呈现历史行动者的逻辑自洽、恐惧、使命叙事和自我辩护，但必须通过原文已有的公开文件、行动、制度安排、外部行为和可核查材料表达；不要替人物补写内心独白。',
    '总目标：保持历史散文气质；保持作者立场，但立场藏在材料取舍、动词、句子重心和结构推进里，不变成口号；保持事实准确，不能编造日记、讲话、文件名、报纸标题、心理活动、具体场景；降低 AI 味，删除模板化、过度顺滑、过度总结、全知旁白式表达；让文章更像一个追问者写出的历史散文，而不是模型生成的历史讲稿。',
    '事实与史料要求：任何具体日期、文件、人物身份、引文、数字、机构关系、战役结果，都必须可核查。不确定的内容不能写成确定事实。不要编造人物心理；能用外部行为、文件、公开表态、制度后果表达，就不要进入人物内心。不要编造现场细节，除非原文或史料明确支持。引用文献可以保留，但不要在正文里新增脚注。引文必须尽量短，且不能改写成伪引文；概括材料时说“某书指出”“某材料显示”，不要伪装成直接原话。',
    '文风要求：用历史散文写法，不要写成干巴巴的说明文。从具体场景、器物、地点、制度动作进入，再逐渐上升到结构判断。抽象判断要由事实托住，不要单独喊口号。语言可以冷，可以有锋利感，但不能虚张声势。允许文学性，但比喻必须从材料里长出来；铁路、账册、密约、神庙、矿山、档案、粮食、军靴、地图这些来自正文材料的意象可以用，不要凭空制造巨大隐喻系统。段落之间要有推进，不要每段都用“然而”“与此同时”“更重要的是”机械连接。不要过度文言化；引用文献或历史文本可保留原貌，正文叙述以现代汉语为主，少量文言词只用于压节奏。避免欧化句式，尤其是过长的抽象名词链、被动套话、概念堆叠。',
    '必须排查并尽量删除的 AI 味：模板化判断、先否定一个说法再抬出另一个判断的强调句、全知心理旁白、过度工整的总结句、舞台化或剧本化表达、口号化反讽、过度顺滑、空泛抽象词、人造金句、过度解释。让材料自己压出判断，不要像老师一样解释读者应该怎么理解。引号、书名号可以正常使用。',
    '修改方式：不要大面积重写到失去原作者语气。优先改明显 AI 味、事实风险、语序错乱、欧化句式。事实风险高的段落先降级为概括表达，或删除具体细节。文风太口号化的段落改成具体场景、制度动作和后果。太像百科时加入现场质感，但不能编造细节。太像小说时删掉无来源心理和戏剧细节，压回史料。保留作者的冷峻、追问、系统感和立场锋利度。',
    '',
    '[风格要求]',
    '- 删除AI味转折词：然而、但是、不过、此外、与此同时、不仅如此、值得注意的是、尽管如此、不可否认',
    '- 遇到二分转折和伪二分强调句，必须拆掉整套句法骨架。不要把"不是……而是……"表面改成"不是……是……"、"并非……而……"或其他同构句。改成正向事实句：先写事实主体、制度动作和后果，不靠否定前项制造重量。',
    '- 删除空洞修辞、漂亮对仗和概念口号。凡是不能落到文件、行动、数字、人物处境、制度后果的句子，要么压实为事实，要么删掉。',
    '- 短判断句不要独立成段：每隔几段甩一句哲理警句单独成段（如“速度是核心变量。”“空间是意识形态的混凝土形式。”）是AI节奏指纹。示范——把这种独立金句并入相邻段落的论证里，让它由前文事实带出，而不是空降一句口号。',
    '- 删除括号注释：中文（）和英文()内的解释性文字，信息融入正文',
    '- 段落长短不规则，不要工整对称',
    '- 句子短的时候像钉子，长的时候像绳索',
    '- 判断藏在动词里，不在形容词里',
    '- 连续两句不得以同一个字开头',
    '- 宏观判断采用正向直陈：事实主体 -> 制度动作 -> 后果',
    '',
    '[正文开始]',
    body, // 原文正文作为被润色对象，模型只能改这段。
    '[正文结束]',
  ].filter(Boolean).join('\n');
}
